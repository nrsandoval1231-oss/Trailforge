"""Evidence-bounded reporting helpers for the dedicated historical cohort."""
from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path
from typing import Any

from athena_arena.contracts import canonical_hash

from .foundation import Scenario
from .historical_cases import EvidenceSourceRef, HistoricalCase
from .policies import PreRfpBaselineV1
from .runner import verify_experiment
from .world import TemporalWorld

UNKNOWN = "UNKNOWN"
_ACTIONS = {"RESEARCH", "PREPARE", "BID_REVIEW"}
_SOLICITATION_RELEASE = re.compile(
    r"\b(?:request for proposals?|rfp|invitation to bid|generation solicitation)\b.*\b(?:released|issued|published)\b|\b(?:released|issued|published)\b.*\b(?:request for proposals?|rfp|invitation to bid|generation solicitation)\b",
    re.IGNORECASE,
)


def _parse_timestamp(value: Any, field: str) -> datetime:
    if not isinstance(value, str):
        raise ValueError(f"{field} must be an ISO timestamp")
    try:
        result = datetime.fromisoformat(value)
    except ValueError as exc:
        raise ValueError(f"{field} must be an ISO timestamp") from exc
    if result.tzinfo is None or result.utcoffset() is None:
        raise ValueError(f"{field} must include a timezone")
    return result


def _recompute_pre_rfp(scenario: Scenario) -> list[dict[str, Any]]:
    policy = PreRfpBaselineV1()
    world = TemporalWorld(scenario, policy.policy_id, policy)
    world.run()
    if not world.ledger.verify():
        raise ValueError("recomputed pre-RFP ledger verification failed")
    return [{"simulation_time": item.simulation_time.isoformat(), "action": item.action,
             "visible_evidence_ids": list(item.visible_evidence_ids), "forecast": dict(item.forecast),
             "record_hash": item.record_hash} for item in world.ledger.records]


def _verify_replay(case: HistoricalCase, scenario: Scenario, replay: dict[str, Any]) -> list[dict[str, Any]]:
    """Verify persisted BASELINE_A artifacts and recompute PRE_RFP_BASELINE_V1.

    Caller-provided ledger flags and decision rows are intentionally ignored.
    """
    if not isinstance(replay, dict):
        raise TypeError("replay must be the result generated by replay_case")
    if (replay.get("case_id") != case.case_id or replay.get("procurement_family_id") != case.procurement_family_id
            or replay.get("case_hash") != case.case_hash):
        raise ValueError("replay does not bind the loaded case")
    experiment_dir = replay.get("experiment_dir")
    if not isinstance(experiment_dir, str) or not experiment_dir:
        raise ValueError("replay has no persisted experiment directory")
    manifest, artifacts = verify_experiment(Path(experiment_dir))
    if (manifest.get("scenario_hash") != canonical_hash(scenario)
            or artifacts["config.json"].get("policy_id") != "BASELINE_A"
            or replay.get("experiment_manifest_hash") != manifest.get("manifest_hash")):
        raise ValueError("replay does not bind a verified BASELINE_A experiment for the loaded scenario")
    return _recompute_pre_rfp(scenario)


def _valid_milestone(refs: dict[str, EvidenceSourceRef], item: dict[str, Any]) -> dict[str, Any] | None:
    ref = refs.get(item.get("evidence_id"))
    if ref is None or item.get("kind") != "GENERATION_SOLICITATION_RELEASE" or item.get("verification") != "VERIFIED":
        return None
    claims, quote = ref.reviewed_claims, ref.source_quote
    semantic_quote, event_at = claims.get("milestone_semantic_evidence_quote"), claims.get("release_event_at")
    proof = ref.extra_fields.get("archive_version_proof") if ref.extra_fields else None
    if (not isinstance(semantic_quote, str) or not semantic_quote.strip() or semantic_quote not in quote
            or not _SOLICITATION_RELEASE.search(semantic_quote) or not isinstance(event_at, str)
            or event_at not in semantic_quote
            or item.get("at") != event_at or not isinstance(proof, dict)
            or ref.extra_fields.get("observation_kind") == "ARCHIVE_REPRESENTATION_OBSERVATION"):
        return None
    try:
        _parse_timestamp(event_at, "release_event_at")
    except ValueError:
        return None
    return {**item, "at": event_at}


def select_verified_generation_solicitation(case: HistoricalCase) -> dict[str, Any] | None:
    """Select only the earliest predeclared, source-bound solicitation release."""
    refs = {item.evidence_id: item for item in case.evidence_sources}
    candidates = [_valid_milestone(refs, item) for item in case.extra_fields.get("historical_milestones", [])]
    candidates = [item for item in candidates if item is not None]
    return min(candidates, key=lambda item: _parse_timestamp(item["at"], "milestone.at")) if candidates else None


def _actionable_at(decisions: list[dict[str, Any]], refs: dict[str, EvidenceSourceRef]) -> str | None:
    for decision in decisions:
        if decision.get("action") not in _ACTIONS:
            continue
        at = _parse_timestamp(decision.get("simulation_time"), "decision simulation_time")
        organizations = set()
        for evidence_id in decision.get("visible_evidence_ids", []):
            ref = refs.get(evidence_id)
            if ref is None or not ref.replay_included or _parse_timestamp(ref.verified_available_at, "verified_available_at") > at:
                continue
            claims, quote = ref.reviewed_claims, ref.source_quote
            org, org_quote, route_quote = (claims.get("buyer_organization"), claims.get("organization_evidence_quote"),
                                            claims.get("direct_route_evidence_quote"))
            route_value = next((claims.get(field) for field in ("direct_contact_url", "direct_contact_email", "direct_contact_phone")
                                if isinstance(claims.get(field), str) and claims[field].strip().upper() != UNKNOWN), None)
            if (isinstance(org, str) and org.strip() and org.strip().upper() != UNKNOWN
                    and claims.get("project_responsibility_supported") is True
                    and isinstance(org_quote, str) and org_quote.strip() and org_quote in quote
                    and org.strip().casefold() in org_quote.casefold()
                    and claims.get("usable_direct_route") is True and isinstance(route_quote, str) and route_quote.strip()
                    and route_quote in quote and isinstance(route_value, str) and route_value.strip()
                    and route_value.strip().upper() != UNKNOWN and route_value.casefold() in route_quote.casefold()):
                organizations.add(org.strip().casefold())
        if len(organizations) == 1:
            return decision["simulation_time"]
    return None


def historical_lead_status(lead_seconds: float | None) -> str:
    """Classify only already-verified lead arithmetic."""
    if lead_seconds is None:
        return UNKNOWN
    return "SUPPORTED" if lead_seconds >= 0 else "NO_EARLY_ADVANTAGE"


def build_case_report(case: HistoricalCase, scenario: Scenario, replay: dict[str, Any], research_burden: dict[str, Any]) -> dict[str, Any]:
    """Build a report only from a loaded case and a verified persisted replay."""
    if not isinstance(case, HistoricalCase) or not isinstance(scenario, Scenario):
        raise TypeError("build_case_report requires HistoricalCase and Scenario from load_case")
    decisions = _verify_replay(case, scenario, replay)
    refs = {item.evidence_id: item for item in case.evidence_sources}
    milestone, first_actionable = select_verified_generation_solicitation(case), _actionable_at(decisions, refs)
    first_surface = next((item for item in decisions if item.get("action") in _ACTIONS), None)
    surface_refs = []
    if first_surface:
        surface_at = _parse_timestamp(first_surface["simulation_time"], "surface time")
        surface_refs = [refs[key] for key in first_surface["visible_evidence_ids"] if key in refs and refs[key].replay_included
                        and _parse_timestamp(refs[key].verified_available_at, "verified_available_at") <= surface_at]
    lead_seconds = None if not milestone or not first_actionable else (_parse_timestamp(milestone["at"], "milestone.at") - _parse_timestamp(first_actionable, "first_buyer_actionable_at")).total_seconds()
    missing = []
    if not milestone:
        missing.append("NO_VERIFIED_EXPLICIT_GENERATION_SOLICITATION_RELEASE")
    if not first_actionable:
        missing.append("NO_POLICY_SURFACE_WITH_SUPPORTED_RESPONSIBILITY_AND_USABLE_DIRECT_ROUTE")
    return {"case_id": case.case_id, "procurement_family_id": case.procurement_family_id,
            "mode": replay.get("mode", "BACKTRACE"), "policy_id": "PRE_RFP_BASELINE_V1",
            "first_policy_surface_at": first_surface["simulation_time"] if first_surface else UNKNOWN,
            "first_buyer_actionable_at": first_actionable or UNKNOWN,
            "verified_generation_solicitation": milestone or UNKNOWN, "historical_lead_seconds": lead_seconds,
            "lead_status": historical_lead_status(lead_seconds),
            "available_evidence_at_surface": [{"evidence_id": item.evidence_id, "capture_id": item.capture_id, "source_url": item.source_url, "source_quote": item.source_quote, "claims": item.reviewed_claims} for item in surface_refs],
            "missing_reasons": missing, "invalidators": case.extra_fields.get("invalidators", []),
            "misses_vs_insufficient_evidence": "INSUFFICIENT_EVIDENCE" if missing else "NO_MISS_ESTABLISHED",
            "outcome": case.outcome, "research_burden": research_burden, "discovery_credit": False}
